#!/usr/bin/env python3
"""The launcher icon, written for Android from `icon.png`.

`icon.png` is the author's own artwork [author, 2026-11-20]: the gold crown
on the russet field. Android draws a launcher icon as two layers under a
mask whose shape the launcher chooses, and guarantees only a circle 66 dp
across out of the 108 dp layer; so this lifts the crown off its field,
scales it to sit inside that circle, and writes:

  * `mipmap-*/ic_launcher_foreground.png`, the crown on transparency, at
    each density;
  * `values/ic_launcher_background.xml`, the field's colour;
  * `mipmap-anydpi/ic_launcher.xml`, the adaptive icon joining them, the
    crown doubling as the monochrome layer a themed launcher tints.

Nothing is cropped: the crown's whole extent stays inside the safe circle.
Run it when the artwork changes; it needs Pillow, which the gate does not.
"""
import math
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, 'icon.png')
RES = os.path.join(HERE, '..', 'mobile', 'android', 'app', 'src', 'main', 'res')

# The layer is 108 dp; the crown's bounding circle is held to 64 of the 66
# the mask guarantees, a dp's margin all round.
LAYER_DP, RADIUS_DP = 108, 32
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
# The source's edge carries a one-pixel frame that is not part of the art.
FRAME = 1


def field(im):
    """The field's colour: the most common one."""
    return max(im.getcolors(im.width * im.height))[1]


def lifted(im, ground):
    """The crown on transparency: each pixel's alpha its distance from the
    field along the field-to-gold line, its colour the gold, so the art's
    own antialiasing becomes the alpha edge."""
    px = im.load()
    far = max(((x, y) for y in range(FRAME, im.height - FRAME)
               for x in range(FRAME, im.width - FRAME)),
              key=lambda p: sum(abs(a - b) for a, b in zip(px[p], ground)))
    gold = px[far]
    span = [g - f for g, f in zip(gold, ground)]
    norm = sum(s * s for s in span)
    out = Image.new('RGBA', im.size, gold + (0,))
    op = out.load()
    for y in range(FRAME, im.height - FRAME):
        for x in range(FRAME, im.width - FRAME):
            a = sum((p - f) * s for p, f, s in zip(px[x, y], ground, span)) / norm
            op[x, y] = gold + (round(255 * min(1.0, max(0.0, a))),)
    return out


def main():
    im = Image.open(SOURCE).convert('RGB')
    ground = field(im)
    crown = lifted(im, ground)
    alpha = crown.getchannel('A').load()
    pts = [(x, y) for y in range(crown.height) for x in range(crown.width)
           if alpha[x, y] > 8]
    cx = (min(p[0] for p in pts) + max(p[0] for p in pts)) / 2
    cy = (min(p[1] for p in pts) + max(p[1] for p in pts)) / 2
    reach = max(math.hypot(x - cx, y - cy) for x, y in pts)
    for name, scale in DENSITIES.items():
        side = round(LAYER_DP * scale)
        k = RADIUS_DP * scale / reach
        # Crop a square about the crown's centre that maps onto the layer.
        half = side / 2 / k
        box = (round(cx - half), round(cy - half), round(cx + half), round(cy + half))
        layer = Image.new('RGBA', (box[2] - box[0], box[3] - box[1]), (0, 0, 0, 0))
        layer.paste(crown, (-box[0], -box[1]))
        layer = layer.resize((side, side), Image.LANCZOS)
        d = os.path.join(RES, f'mipmap-{name}')
        os.makedirs(d, exist_ok=True)
        layer.save(os.path.join(d, 'ic_launcher_foreground.png'), optimize=True)
    with open(os.path.join(RES, 'values', 'ic_launcher_background.xml'), 'w') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n'
                '<!-- Generated by crates/brand/icon.py from crates/brand/icon.png. Do not edit. -->\n'
                '<resources>\n'
                '    <color name="ic_launcher_background">#FF%02X%02X%02X</color>\n'
                '</resources>\n' % ground)
    d = os.path.join(RES, 'mipmap-anydpi')
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, 'ic_launcher.xml'), 'w') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n'
                '<!-- Generated by crates/brand/icon.py from crates/brand/icon.png. Do not edit. -->\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@color/ic_launcher_background" />\n'
                '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
                '    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />\n'
                '</adaptive-icon>\n')
    print(f'field #{ground[0]:02X}{ground[1]:02X}{ground[2]:02X}, crown radius {reach:.1f} px '
          f'about ({cx:.1f}, {cy:.1f}), {len(DENSITIES)} densities')


if __name__ == '__main__':
    main()
