#!/usr/bin/env python3
"""The shell's look, written for each client from `tokens.toml`.

One file names every colour, both typefaces and the pairs a screen draws one
on the other [author, 2026-11-18: one source for a coherent brand]; this
writes each platform's copy of it:

  * `Tokens.kt`, the Android shell's values, which `Palette` reads;
  * `colors.xml`, the dark set as resources, which the Android theme wears;
  * `tokens.css`, the desktop window's custom properties and font faces.

And it **checks the floor before it writes anything**: every declared pair
clears the contrast floor in both modes, and the rail's ink reads on the
rail's own colours and on every identity colour. A colour that fails is
refused here, for every platform at once.

    generate.py           write the copies
    generate.py --check   write nothing; exit 1 if a copy has drifted or a
                          pair is under the floor (the gate's mode)

Report the numbers, not a state: the check names each drifted file and each
pair under the floor with its ratio.
"""
import os
import re
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
CRATES = os.path.abspath(os.path.join(HERE, '..'))
SOURCE = os.path.join(HERE, 'tokens.toml')
ANDROID = os.path.join(CRATES, 'mobile', 'android', 'app', 'src', 'main')
KOTLIN = os.path.join(ANDROID, 'kotlin', 'com', 'comptus', 'fueros', 'Tokens.kt')
XML = os.path.join(ANDROID, 'res', 'values', 'colors.xml')
CSS = os.path.join(CRATES, 'desktop', 'ui', 'tokens.css')

# The set's names, in the order every copy writes them.
SET = ['ground', 'chrome', 'sunken', 'control', 'ink', 'muted', 'sub', 'rule',
       'accent', 'onAccent', 'warn', 'avatar']
RAIL = ['rail', 'orb', 'ink', 'divider', 'count', 'gold', 'silver', 'ruleOnly']

HEAD = 'Generated by crates/brand/generate.py from crates/brand/tokens.toml. Do not edit.'


def notes():
    """The trailing comment on each `key = "#RRGGBB"` line, by table and key,
    since tomllib keeps no comments and the copies want them."""
    out, table = {}, None
    with open(SOURCE, encoding='utf-8') as f:
        for line in f:
            m = re.match(r'\[(\w+)\]\s*$', line)
            if m:
                table = m.group(1)
                continue
            m = re.match(r'(\w+)\s*=\s*"#[0-9A-Fa-f]{6}"\s*#\s*(.+)$', line)
            if m and table:
                out[(table, m.group(1))] = m.group(2).strip()
    return out


def rgb(hex6):
    if not re.fullmatch(r'#[0-9A-Fa-f]{6}', hex6):
        raise SystemExit(f'tokens.toml: {hex6!r} is not #RRGGBB')
    return int(hex6[1:], 16)


def luminance(c):
    def ch(v):
        v /= 255.0
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    return 0.2126 * ch((c >> 16) & 0xFF) + 0.7152 * ch((c >> 8) & 0xFF) + 0.0722 * ch(c & 0xFF)


def contrast(a, b):
    x, y = luminance(a), luminance(b)
    return (max(x, y) + 0.05) / (min(x, y) + 0.05)


def under_floor(t):
    """Every declared pair, and the rail's own, that does not clear the floor."""
    floor = t['contrast']['floor']
    out = []
    for mode in ('dark', 'light'):
        for ink, surface in t['contrast']['drawn']:
            r = contrast(rgb(t[mode][ink]), rgb(t[mode][surface]))
            if r < floor:
                out.append(f'{mode}: {ink} on {surface} is {r:.2f}:1')
    rail = t['rail']
    for surface in ('rail', 'orb', 'count'):
        r = contrast(rgb(rail['ink']), rgb(rail[surface]))
        if r < floor:
            out.append(f'rail: ink on {surface} is {r:.2f}:1')
    for i in t['identity']:
        r = contrast(rgb(rail['ink']), rgb(i['colour']))
        if r < floor:
            out.append(f'identity: rail ink on {i["name"]} is {r:.2f}:1')
    return out


def screaming(name):
    return re.sub(r'([a-z])([A-Z])', r'\1_\2', name).upper()


def kotlin(t, n):
    def argb(hex6):
        return f'0xFF{hex6[1:].upper()}.toInt()'

    def block(obj, table, keys):
        lines = [f'    object {obj} {{']
        for k in keys:
            if (table, k) in n:
                lines.append(f'        /** {n[(table, k)]} */')
            lines.append(f'        const val {screaming(k)} = {argb(t[table][k])}')
        lines.append('    }')
        return lines

    out = [f'// {HEAD}', 'package com.comptus.fueros', '',
           '/** **The shell\'s look as `crates/brand/tokens.toml` names it**, for',
           ' *  [Palette] to read. The same file writes the desktop\'s copy. */',
           'object Tokens {',
           '    /** The typeface for people\'s words, navigation and headings. */',
           f'    const val SANS = "{t["type"]["sans"]}"',
           '    /** The typeface for the machine\'s voice. */',
           f'    const val MONO = "{t["type"]["mono"]}"',
           '    /** The contrast floor for anything that must be read (WCAG AA). */',
           f'    const val FLOOR = {t["contrast"]["floor"]}', '']
    out += block('Dark', 'dark', SET) + ['']
    out += block('Light', 'light', SET) + ['']
    out += block('Rail', 'rail', RAIL) + ['']
    out.append('    /** An identity\'s colours, in the order a new identity takes them. */')
    out.append('    val IDENTITY: List<Pair<String, Int>> = listOf(')
    for i in t['identity']:
        out.append(f'        "{i["name"]}" to {argb(i["colour"])},')
    out.append('    )')
    out.append('')
    out.append('    /** Which ink goes on which surface, declared. */')
    out.append('    val DRAWN: List<Pair<String, String>> = listOf(')
    for ink, surface in t['contrast']['drawn']:
        out.append(f'        "{ink}" to "{surface}",')
    out.append('    )')
    out.append('}')
    return '\n'.join(out) + '\n'


def xml(t):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           f'<!-- {HEAD}',
           '     The dark set as resources, because a theme is what restyles every',
           '     Activity at once and a theme\'s values must be resources. -->',
           '<resources>']
    for k in SET:
        out.append(f'    <color name="{k}">#FF{t["dark"][k][1:].upper()}</color>')
    out.append('</resources>')
    return '\n'.join(out) + '\n'


def css(t, n):
    def prop(k):
        return '--' + re.sub(r'([a-z])([A-Z])', r'\1-\2', k).lower()

    def block(sel, table, keys, prefix=''):
        lines = [f'{sel} {{']
        for k in keys:
            note = f'  /* {n[(table, k)]} */' if (table, k) in n else ''
            name = prop(k) if not prefix else f'--{prefix}-' + prop(k)[2:]
            lines.append(f'  {name}: {t[table][k]};{note}')
        return lines

    out = [f'/* {HEAD} */', '',
           '/* The faces are crates/brand/res/font\'s, which the window serves',
           '   under fonts/; a script they do not cover falls back to the',
           '   system\'s own sans and mono. */']
    for family, stem in ((t['type']['sans'], 'geist'), (t['type']['mono'], 'geist_mono')):
        for style, suffix in (('normal', ''), ('italic', '_italic')):
            out += ['@font-face {',
                    f'  font-family: "{family}";',
                    f'  src: url("fonts/{stem}{suffix}.ttf") format("truetype");',
                    '  font-weight: 100 900;',
                    f'  font-style: {style};',
                    '}']
    out += ['', '/* Dark is what a person meets first; light is an option. */']
    out += block(':root', 'dark', SET)
    out += [f'  --sans: "{t["type"]["sans"]}", system-ui, sans-serif;',
            f'  --mono: "{t["type"]["mono"]}", ui-monospace, monospace;']
    for k in RAIL:
        note = f'  /* {n[("rail", k)]} */' if ('rail', k) in n else ''
        name = '--rail' if k == 'rail' else '--rail-' + prop(k)[2:]
        out.append(f'  {name}: {t["rail"][k]};{note}')
    for i in t['identity']:
        out.append(f'  --identity-{i["name"].lower()}: {i["colour"]};')
    out.append('}')
    out.append('')
    out += block(':root[data-mode="light"]', 'light', SET)
    out.append('}')
    return '\n'.join(out) + '\n'


def main():
    check = '--check' in sys.argv[1:]
    with open(SOURCE, 'rb') as f:
        t = tomllib.load(f)
    for mode in ('dark', 'light'):
        missing = [k for k in SET if k not in t[mode]]
        if missing:
            raise SystemExit(f'tokens.toml: [{mode}] lacks {", ".join(missing)}')
    failing = under_floor(t)
    for stem in ('geist', 'geist_italic', 'geist_mono', 'geist_mono_italic'):
        if not os.path.isfile(os.path.join(HERE, 'res', 'font', stem + '.ttf')):
            failing.append(f'res/font/{stem}.ttf is named and not held')
    for f in failing:
        print(f'UNDER THE FLOOR {t["contrast"]["floor"]}: {f}')
    if failing and not check:
        print(f'brand: nothing written; {len(failing)} under the floor')
        return 1
    n = notes()
    copies = {KOTLIN: kotlin(t, n), XML: xml(t), CSS: css(t, n)}
    drifted = []
    for path, text in copies.items():
        held = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if held == text:
            continue
        if check:
            drifted.append(os.path.relpath(path, CRATES))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8') as f:
                f.write(text)
            print(f'wrote {os.path.relpath(path, CRATES)}')
    for d in drifted:
        print(f'DRIFTED from tokens.toml: {d} (run crates/brand/generate.py)')
    pairs = 2 * len(t['contrast']['drawn']) + 3 + len(t['identity'])
    print(f'brand: {len(copies)} copies, {len(drifted)} drifted; '
          f'{pairs} pairs checked, {len(failing)} under the floor')
    return 1 if failing or drifted else 0


if __name__ == '__main__':
    sys.exit(main())
